import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { inspectRuntime, downloadPlan, withRuntimeCopy } from "../../scripts/prepare-dsh-runtime.mjs";

function fixture() {
  const root = mkdtempSync(join(tmpdir(), "bigfish-runtime-check-"));
  const source = join(root, "source"), primary = join(root, "resources/primary-runtime");
  const put = (path: string, value: string | object) => { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, typeof value === "string" ? value : JSON.stringify(value)); };
  const manifest = { desktopVersion: "imported", platform: "win32", arch: "x64", payloadDigest: "a".repeat(64), python: "3.12.14", node: "24.21.0", pnpm: "11.8.0", pythonPackages: { "python-docx": "1.2.0" } };
  put(join(source, "package.json"), { version: "current", packageManager: "pnpm@11.28.5" });
  put(join(source, "scripts/primary-runtime/lock.json"), { pythonVersion: manifest.python, nodeVersion: manifest.node, pythonRelease: "20260901", pythonPackages: manifest.pythonPackages,
    targets: { "win-x64": { nodeArchive: "win-x64.zip", nodeSha256: "b".repeat(64), pythonTarget: "x86_64-pc-windows-msvc", pythonSha256: "c".repeat(64), wheels: [{ url: "https://files.pythonhosted.org/native.whl", sha256: "d".repeat(64) }] } }, wheels: [] });
  put(join(primary, "runtime.json"), manifest);
  for (const file of ["dependencies/python/python.exe", "dependencies/node/bin/node.exe", "dependencies/pnpm/bin/pnpm.mjs"]) put(join(primary, file), "synthetic");
  put(join(primary, "dependencies/pnpm/package.json"), { name: "pnpm", version: manifest.pnpm });
  for (const skill of ["office", "office-docx", "office-pptx", "office-xlsx", "office-export-pdf", "office-recalculate", "office-render"]) put(join(primary, "../office-skills", skill, "SKILL.md"), "synthetic");
  return { root, source, primary, manifest, put, close: () => rmSync(root, { recursive: true, force: true }) };
}

test("runtime inspection preserves imported provenance and cannot claim native/tool verification", () => {
  const f = fixture();
  try {
    const result = inspectRuntime(f.primary, f.source);
    assert.equal(result.status, "inspected"); assert.equal(result.nativeSmokePassed, false); assert.equal(result.allDshToolsVerified, false);
    assert.equal(result.manifest.desktopVersion, "imported"); assert.equal(result.manifest.pnpm, "11.8.0");
    assert.equal(result.warnings.length, 1); assert.ok(result.warnings[0].includes("not a source-identical build"));
    assert.equal(result.primaryInventory.files, 5); assert.equal(result.officeInventory.files, 7);
  } finally { f.close(); }
});

test("runtime inspection rejects empty stub, missing entry point, and missing sibling Office skill", () => {
  for (const removed of ["dependencies/python/python.exe", "../office-skills/office-render/SKILL.md"]) {
    const f = fixture();
    try { rmSync(join(f.primary, removed)); assert.throws(() => inspectRuntime(f.primary, f.source), /Required runtime file missing/); }
    finally { f.close(); }
  }
  const f = fixture();
  try { f.put(join(f.primary, "runtime.json"), {}); assert.throws(() => inspectRuntime(f.primary, f.source), /Windows x64/); }
  finally { f.close(); }
});

test("runtime inspection rejects mismatched interpreter, Python distributions, and pnpm identity", () => {
  for (const change of [{ python: "3.12.13" }, { pythonPackages: {} }, { pnpm: "11.28.5" }]) {
    const f = fixture();
    try { f.put(join(f.primary, "runtime.json"), { ...f.manifest, ...change }); assert.throws(() => inspectRuntime(f.primary, f.source)); }
    finally { f.close(); }
  }
});

test("download plan uses source-locked official URLs and hashes without downloading", () => {
  const f = fixture();
  try {
    const plan = downloadPlan(f.source);
    assert.equal(plan.length, 3); assert.equal(plan[0].url, "https://nodejs.org/dist/v24.21.0/node-v24.21.0-win-x64.zip");
    assert.ok(plan[1].url.includes("astral-sh/python-build-standalone/releases/download/20260901/cpython-3.12.14%2B20260901"));
    assert.equal(plan[2].sha256, "d".repeat(64));
  } finally { f.close(); }
});

test("native verification copy isolates writes and is cleaned on success and failure", () => {
  for (const fail of [false, true]) {
    const f = fixture(); let staged = "";
    try {
      const before = readFileSync(join(f.primary, "runtime.json"), "utf8");
      const verify = () => withRuntimeCopy(f.primary, (copy: string) => {
        staged = dirname(copy);
        assert.ok(existsSync(join(copy, "../office-skills/office/SKILL.md")));
        writeFileSync(join(copy, "runtime.json"), "mutated copy");
        writeFileSync(join(copy, "cache.pyc"), "generated bytecode");
        if (fail) throw new Error("synthetic native smoke failure");
        return "verified";
      });
      if (fail) assert.throws(verify, /synthetic native smoke failure/); else assert.equal(verify(), "verified");
      assert.ok(staged); assert.equal(existsSync(staged), false);
      assert.equal(readFileSync(join(f.primary, "runtime.json"), "utf8"), before);
      assert.equal(existsSync(join(f.primary, "cache.pyc")), false);
    } finally { f.close(); }
  }
});
